func matchTier(name string, table []part) (int, string) {
	n := strings.ToLower(name)
	best, bestKey := 0, ""
	for _, p := range table {
		if strings.Contains(n, p.key) && len(p.key) > len(bestKey) {
			best, bestKey = p.tier, p.key
		}
	}
	return best, bestKey
}

func apiBalance() map[string]interface{} {
	info := apiSysInfo() // использует кэш
	cpu, _ := info["cpu"].(string)
	gpu, _ := info["gpu"].(string)
	// если GPU две (встроенная + дискретная) — берём самую мощную для оценки
	gpuT := 0
	for _, g := range strings.Split(gpu, " + ") {
		if t, _ := matchTier(g, gpuTiers); t > gpuT {
			gpuT = t
		}
	}
	cpuT, _ := matchTier(cpu, cpuTiers)

	verdict, kind := balanceVerdict(cpuT, gpuT)
	return map[string]interface{}{
		"cpu": cpu, "gpu": gpu, "cpuTier": cpuT, "gpuTier": gpuT,
		"verdict": verdict, "kind": kind,
		"known": cpuT > 0 && gpuT > 0,
	}
}

// kind: "gpu" — упор в видеокарту, "cpu" — упор в процессор, "balanced", "unknown"
func balanceVerdict(cpuT, gpuT int) (string, string) {
	if cpuT == 0 && gpuT == 0 {
		return "Не удалось распознать процессор и видеокарту — но это не влияет на работу оптимизаций.", "unknown"
	}
	if cpuT == 0 || gpuT == 0 {
		return "Распознал только одну из деталей. Оценка баланса неполная.", "unknown"
	}
	diff := cpuT - gpuT
	switch {
	case diff >= 12:
		return "Видеокарта — главное ограничение. Процессор с большим запасом: упор идёт в GPU почти при любом качестве, а на высоком разрешении (4K, DLAA) — тем более. CPU раскрывается только в киберспорте на низких настройках ради сотен FPS.", "gpu"
	case diff <= -12:
		return "Процессор может стать узким местом — особенно на низких и средних настройках с высоким FPS. На высоком качестве и разрешении нагрузка смещается на видеокарту, и дисбаланс сглаживается.", "cpu"
	default:
		return "Связка сбалансирована. На высоком качестве упор в видеокарту, в режимах «производительность»/низкие настройки нагрузка смещается на процессор — это нормально.", "balanced"
	}
}
